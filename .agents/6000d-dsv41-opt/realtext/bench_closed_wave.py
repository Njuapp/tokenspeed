#!/usr/bin/env python3
"""Closed-wave decode benchmark (stdlib only), same method as the published numbers.

One wave = CC requests released together (8192-token prompts from the bank, 1024 output
tokens, temperature 0, ignore_eos, streaming, round-robin routed over DP ranks).
Decode window = [all requests have produced their first token, first request finished].
  window throughput (tok/s) = output tokens generated by all requests inside the window / window
  TPOT (ms)                 = CC * 1000 / window throughput   (per-request time per output token)
  accept                    = window tokens / window decode cycles (DSpark tokens per cycle)
Prefill is excluded. Sequence: smoke chat, 32-token warmup wave, one discarded 1024-token
wave (finishes JIT/graph warmup), then --waves measured waves; the median wave is reported.
A wave is VALID if every request returns 8192 prompt / 1024 output tokens with 0 cached
tokens and the window holds >= 100 decode cycles for every request.
"""

import argparse
import json
import os
import statistics
import threading
import time
import urllib.request

p = argparse.ArgumentParser()
p.add_argument("--url", required=True)
p.add_argument("--model", default="deepseek-v4.1-flash")
p.add_argument("--bank", required=True)
p.add_argument("--cc", type=int, default=128)
p.add_argument(
    "--dp", type=int, default=8, help="attention DP size (8 for EP8, 16 for EP16)"
)
p.add_argument("--waves", type=int, default=3)
p.add_argument("--max-tokens", type=int, default=1024)
p.add_argument("--out", required=True)
a = p.parse_args()
os.makedirs(a.out, exist_ok=True)
bank = json.load(open(a.bank))["prompts"]


def post(path, body, timeout=600):
    req = urllib.request.Request(
        a.url + path,
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(req, timeout=timeout) as f:
        return f.read()


def one(i, max_tokens, tag, barrier, results):
    item = bank[i % len(bank)]
    payload = {
        "input_ids": item["prompt_token_ids"],
        "rid": f"{tag}-{i:04d}",
        "stream": True,
        "routed_dp_rank": i % a.dp,
        "sampling_params": {
            "max_new_tokens": max_tokens,
            "temperature": 0,
            "ignore_eos": True,
        },
    }
    events, meta, err = [], {}, None
    req = urllib.request.Request(
        a.url + "/generate",
        data=json.dumps(payload).encode(),
        headers={"Content-Type": "application/json"},
    )
    barrier.wait()
    t0 = time.monotonic()
    try:
        with urllib.request.urlopen(req, timeout=7200) as r:
            for raw in r:
                line = raw.decode(errors="replace").strip()
                if not line.startswith("data:"):
                    continue
                body = line[5:].strip()
                if body == "[DONE]":
                    break
                meta = json.loads(body).get("meta_info", meta)
                events.append((time.monotonic(), int(meta.get("completion_tokens", 0))))
    except Exception as e:
        err = repr(e)
    results[i] = {
        "t_submit": t0,
        "events": events,
        "error": err,
        "meta": {
            k: meta.get(k)
            for k in (
                "prompt_tokens",
                "completion_tokens",
                "cached_tokens",
                "spec_accept_length",
            )
        },
    }


def wave(tag, max_tokens):
    try:
        post("/flush_cache", {}, timeout=120)
    except Exception:
        pass
    results, barrier = [None] * a.cc, threading.Barrier(a.cc)
    ts = [
        threading.Thread(target=one, args=(i, max_tokens, tag, barrier, results))
        for i in range(a.cc)
    ]
    [t.start() for t in ts]
    [t.join() for t in ts]
    with open(os.path.join(a.out, f"{tag}.jsonl"), "w") as f:
        for r in results:
            f.write(json.dumps(r) + "\n")
    return results


def analyze(rows, max_tokens):
    bad = [
        i
        for i, r in enumerate(rows)
        if r is None
        or r["error"]
        or r["meta"]["completion_tokens"] != max_tokens
        or r["meta"]["prompt_tokens"] != 8192
        or (r["meta"]["cached_tokens"] or 0) != 0
        or not r["events"]
    ]
    if bad:
        return {
            "status": "INVALID_REQUESTS",
            "bad": bad[:10],
            "example": rows[bad[0]] and rows[bad[0]]["error"],
        }
    first = [next(t for t, n in r["events"] if n >= 1) for r in rows]
    last = [next(t for t, n in r["events"] if n >= max_tokens) for r in rows]
    t0, t1 = max(first), min(last)
    if t1 <= t0:
        return {"status": "NO_FULL_BATCH_WINDOW"}

    def count(ev, t):
        c = 0
        for te, n in ev:
            if te > t:
                break
            c = n
        return c

    tokens = sum(count(r["events"], t1) - count(r["events"], t0) for r in rows)
    cycles = [sum(1 for te, _ in r["events"] if t0 < te <= t1) for r in rows]
    tps = tokens / (t1 - t0)
    return {
        "status": "VALID" if min(cycles) >= 100 else "SHORT_WINDOW",
        "throughput_tok_s": tps,
        "tpot_ms": a.cc * 1000.0 / tps,
        "accept": tokens / max(1, sum(cycles)),
        "window_s": t1 - t0,
        "min_cycles": min(cycles),
        "prefill_spread_s": t0 - min(r["t_submit"] for r in rows),
    }


chat = json.loads(
    post(
        "/v1/chat/completions",
        {
            "model": a.model,
            "temperature": 0,
            "max_tokens": 256,
            "messages": [{"role": "user", "content": "17+26等于多少？只回答数字。"}],
        },
    )
)
msg = chat["choices"][0]["message"]
smoke = "43" in (msg.get("content") or "") + (msg.get("reasoning_content") or "")
print(
    json.dumps(
        {
            "smoke_17_plus_26": "PASS" if smoke else "FAIL",
            "reply": (msg.get("content") or "")[:80],
        },
        ensure_ascii=False,
    ),
    flush=True,
)
wave("warmup32", 32)
print(
    json.dumps(
        {"discarded_wave": analyze(wave("warmup1024", a.max_tokens), a.max_tokens)}
    ),
    flush=True,
)
waves = []
for k in range(1, a.waves + 1):
    m = analyze(wave(f"wave{k}", a.max_tokens), a.max_tokens)
    m["wave"] = k
    waves.append(m)
    print(json.dumps(m), flush=True)
ok = [w for w in waves if w["status"] == "VALID"]
summary = {"cc": a.cc, "dp": a.dp, "valid_waves": len(ok), "waves": waves}
if ok:
    med = sorted(ok, key=lambda w: w["throughput_tok_s"])[len(ok) // 2]
    summary.update(
        median_throughput_tok_s=round(med["throughput_tok_s"], 1),
        median_tpot_ms=round(med["tpot_ms"], 2),
        median_accept=round(med["accept"], 3),
        throughput_per_gpu=round(med["throughput_tok_s"] / a.dp, 1),
    )
json.dump(summary, open(os.path.join(a.out, "summary.json"), "w"), indent=1)
print("RESULT", json.dumps({k: v for k, v in summary.items() if k != "waves"}))
